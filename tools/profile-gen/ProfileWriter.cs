// Writes the generated entries as one text block, so the hand-written part of profile.yaml stays byte for byte.

using System.Globalization;
using System.Text;

namespace ProfileGen;

static class ProfileWriter
{
    public const string Begin = "  # >>> generated by tools/profile-gen (CRO-8 step 1), do not edit by hand, re-run the tool <<<";
    public const string End = "  # >>> end generated <<<";

    static string Q(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    static string N(double d) => d.ToString("0.###", CultureInfo.InvariantCulture);
    static string List(double[] a) => "[" + string.Join(", ", a.Select(N)) + "]";

    public static string Block(IEnumerable<Entry> entries)
    {
        var sb = new StringBuilder();
        sb.Append(Begin).Append('\n');
        foreach (var e in entries)
        {
            sb.Append("  - name: ").Append(e.Name).Append('\n');
            sb.Append("    label: ").Append(Q(e.Label)).Append('\n');
            if (e.ValueLabels is { } vl)
                sb.Append("    value_labels: { ").Append(string.Join(", ", vl.Select(p => $"\"{p.Key}\": {p.Value}"))).Append(" }\n");
            sb.Append("    class: ").Append(e.Class).Append('\n');
            sb.Append("    group: ").Append(e.Group).Append('\n');
            if (e.Values is { } v) sb.Append("    values: ").Append(List(v)).Append('\n');
            if (e.Range is { } r) sb.Append("    range: ").Append(List(r)).Append('\n');
            if (e.PulseMs is { } p) sb.Append("    pulse_ms: ").Append(p).Append('\n');
            if (e.Counter) sb.Append("    press: counter\n");
            if (e.Display is { } d) sb.Append("    display: ").Append(d).Append('\n');
            if (e.Verify is { } vf) sb.Append("    verify: ").Append(VerifyText(vf)).Append('\n');
            sb.Append("    note: ").Append(Q(string.Join("; ", e.Notes))).Append('\n');
        }
        sb.Append(End).Append('\n');
        return sb.ToString();
    }

    static string VerifyText(Verify v) => v.Kind switch
    {
        "lvar" => $"{{ lvar: {v.Target}, settle_ms: {v.SettleMs} }}",
        "mcdu" => $"{{ mcdu: {v.Target}, settle_ms: {v.SettleMs} }}",
        _ => $"{{ graphql: {v.Target}, scale: {N(v.Scale ?? 1)}, settle_ms: {v.SettleMs} }}",
    };

    /// <summary>Text of the hand-written part: the file without a previous generated block.</summary>
    public static string StripBlock(string text)
    {
        var b = text.IndexOf(Begin, StringComparison.Ordinal);
        if (b < 0) return text;
        var e = text.IndexOf(End, b, StringComparison.Ordinal);
        if (e < 0) throw new InvalidOperationException("profile.yaml has a generated-block start marker but no end marker.");
        var start = text.LastIndexOf('\n', b) + 1;
        var end = text.IndexOf('\n', e) + 1;
        // also drop the blank line that separated the block from the next section
        if (end < text.Length && text[end] == '\n') end++;
        return text[..start] + text[end..];
    }

    /// <summary>Insert the block before the top-level datarefs: key (or at the end if there is none).</summary>
    public static string Insert(string handWritten, string block)
    {
        var at = handWritten.IndexOf("\ndatarefs:", StringComparison.Ordinal);
        if (at < 0) return handWritten.TrimEnd('\n') + "\n\n" + block;
        return handWritten[..(at + 1)] + block + "\n" + handWritten[(at + 1)..];
    }
}
