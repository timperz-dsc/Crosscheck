// draft-report.md and draft-review.csv.

using System.Text;
using System.Text.RegularExpressions;
using Crosscheck.Profiles.Model;

namespace ProfileGen;

static class ReportWriter
{
    static string Csv(string s) => s.Contains(',') || s.Contains('"') ? "\"" + s.Replace("\"", "\"\"") + "\"" : s;
    static string Lower(SyncClass c) => c.ToString().ToLowerInvariant();

    public static string ReviewCsv(IEnumerable<Review> reviews)
    {
        var sb = new StringBuilder("name,scan_value,kind,provisional_class,reason\n");
        foreach (var r in reviews.OrderBy(r => r.Kind).ThenBy(r => r.Reason).ThenBy(r => r.Name, StringComparer.Ordinal))
            sb.Append($"{Csv(r.Name)},{Csv(r.Value)},{r.Kind},{r.ProvisionalClass},{Csv(r.Reason)}\n");
        return sb.ToString();
    }

    /// <summary>
    /// unsynced.csv: the S_/A_ vars still on the review list, with a label. The bridge watches them
    /// read-only and shows "You moved &lt;label&gt; – not synced yet" (CRO-26). Short label unless two clash.
    /// </summary>
    public static string UnsyncedCsv(IEnumerable<Review> reviews)
    {
        var rows = reviews.Where(r => r.Name.StartsWith("S_", StringComparison.Ordinal) || r.Name.StartsWith("A_", StringComparison.Ordinal))
            .Select(r => r.Name).Distinct().Order(StringComparer.Ordinal)
            .Select(n => (Name: n, Label: Rules.LabelOf(n))).ToList();
        // Without a panel around it, a one-word short label ("MODE") is too vague: keep the system ("ENG MODE").
        var clash = rows.GroupBy(r => r.Label.Short).Where(g => g.Count() > 1).SelectMany(g => g).Select(r => r.Name)
            .Concat(rows.Where(r => !r.Label.Short.Contains(' ')).Select(r => r.Name)).ToHashSet();
        var sb = new StringBuilder("name,label\n");
        foreach (var r in rows) sb.Append($"{Csv(r.Name)},{Csv(clash.Contains(r.Name) ? r.Label.Long : r.Label.Short)}\n");
        return sb.ToString();
    }

    public static string Report(Profile profile, List<Entry> entries, List<Review> reviews, List<Pairing> pairings,
        List<string> sample, List<string> scanNames, List<string> profileNames, string scanPath, int excluded, int handKept,
        OverrideFile? overrides = null)
    {
        var sb = new StringBuilder();
        void L(string s = "") => sb.Append(s).Append('\n');

        L("# Fenix A320 profile report (CRO-8 steps 1-3)");
        L();
        L($"Generated by `tools/profile-gen` from `{Path.GetFileName(scanPath)}`. Nothing was run against the sim. Re-running the tool replaces the generated block in `profile.yaml` and this report.");
        L();
        L("## Summary");
        L();
        L($"- scan: {scanNames.Count + excluded} vars; {excluded} dropped by the profile's exclude patterns");
        L($"- hand-written entries kept exactly as they were: {handKept}");
        L($"- generated entries written to `profile.yaml`: {entries.Count}");
        L($"- review list (not in the profile): {reviews.Count}, full list in `draft-review.csv`");
        L($"- profile now: {profile.Vars.Count} vars, {profile.Datarefs?.Count ?? 0} dataref(s), validated with Crosscheck.Profiles");
        L($"- generated labels (entries with the note \"label generated\", for step 3 review): {entries.Count}");
        if (overrides is { Overrides.Count: > 0 })
            L($"- overrides applied from `overrides.yaml` (probe results and owner decisions, CRO-8 step 3): {overrides.Overrides.Count}");
        L();

        if (overrides is { Open.Count: > 0 })
        {
            L("## Still open");
            L();
            L("From `overrides.yaml` (`open:`). Everything on the review list below is open too.");
            L();
            L("| what | vars | why |");
            L("|---|---|---|");
            foreach (var o in overrides.Open)
                L($"| {o.What} | {(o.Vars.Count == 0 ? "" : string.Join(", ", o.Vars.Take(8).Select(v => $"`{v}`")) + (o.Vars.Count > 8 ? $" (+{o.Vars.Count - 8})" : ""))} | {o.Why} |");
            L();
        }
        if (overrides is { Overrides.Count: > 0 })
        {
            L("## Overrides applied");
            L();
            L("| kind | count |");
            L("|---|---|");
            foreach (var g in overrides.Overrides.GroupBy(o => o.Evidence.Split(':')[0]).OrderByDescending(g => g.Count()))
                L($"| {g.Key} | {g.Count()} |");
            L();
        }

        L("## Counts per class (whole profile)");
        L();
        L("| class | hand-written | generated | total |");
        L("|---|---|---|---|");
        foreach (var c in Enum.GetValues<SyncClass>())
        {
            var gen = entries.Count(e => e.Class == Lower(c));
            var total = profile.Vars.Count(v => v.Class == c);
            if (total > 0) L($"| {Lower(c)} | {total - gen} | {gen} | {total} |");
        }
        L();

        L("## Counts per group and class (whole profile)");
        L();
        var classes = Enum.GetValues<SyncClass>().Where(c => profile.Vars.Any(v => v.Class == c)).ToList();
        L("| group | " + string.Join(" | ", classes.Select(Lower)) + " | total |");
        L("|---|" + string.Concat(classes.Select(_ => "---|")) + "---|");
        foreach (var g in profile.Groups)
        {
            var row = classes.Select(c => profile.Vars.Count(v => v.Group == g && v.Class == c)).ToList();
            L($"| {g} | " + string.Join(" | ", row) + $" | {row.Sum()} |");
        }
        L();

        L("## Review list: not in the profile");
        L();
        L("These could not be classified or placed with confidence, so they are not guessed. Full list with scan values: `draft-review.csv`.");
        L();
        L("| reason | count | examples |");
        L("|---|---|---|");
        foreach (var g in reviews.Where(r => r.Kind != "naming").GroupBy(r => Generalise(r.Reason)).OrderByDescending(g => g.Count()))
            L($"| {g.Key} | {g.Count()} | {string.Join(", ", g.Take(4).Select(r => $"`{r.Name}`"))} |");
        L();
        var naming = reviews.Where(r => r.Kind == "naming").GroupBy(r => Prefix(r.Name)).OrderByDescending(g => g.Count()).ToList();
        if (naming.Count > 0)
        {
            L($"Not Fenix naming and not excluded ({naming.Sum(g => g.Count())} vars, by leading token). Add an exclude pattern, or tell me which are aircraft vars:");
            L();
            L("| token | count | examples |");
            L("|---|---|---|");
            foreach (var g in naming.Take(40))
                L($"| `{g.Key}` | {g.Count()} | {string.Join(", ", g.Take(3).Select(r => $"`{r.Name}`"))} |");
            if (naming.Count > 40) L($"| ... | {naming.Skip(40).Sum(g => g.Count())} | {naming.Count - 40} more tokens, see csv |");
            L();
        }

        L("## Effect pairings");
        L();
        L($"{pairings.Count} switches have an effect source. Covers have none (TYPES.md). Pairs marked **lower-half rule** have both an `_L` and a `_U` lamp; the lower half (state ON/OFF) was chosen. Step 2 must confirm them.");
        L();
        L("| switch | effect source | rule |");
        L("|---|---|---|");
        foreach (var p in pairings.OrderBy(p => p.Rule == "lower-half rule" ? 0 : 1).ThenBy(p => p.Switch, StringComparer.Ordinal))
            L($"| `{p.Switch}` | `{p.Target}` | {(p.Rule == "lower-half rule" ? "**lower-half rule**" : p.Rule)} |");
        L();

        L("## Probe deny list (`probe-deny.yaml`)");
        L();
        L("Hits = vars denied, among all scanned aircraft vars / among profile entries. 0 hits would mean a typo in the pattern.");
        L();
        L("| pattern | hits (scan) | hits (profile) | reason |");
        L("|---|---|---|---|");
        var scanHits = DenyList.Hits(scanNames);
        var profileHits = DenyList.Hits(profileNames);
        foreach (var r in DenyList.Rules)
            L($"| `{r.Pattern}` | {scanHits[r]}{(scanHits[r] == 0 ? " **none**" : "")} | {profileHits[r]} | {r.Reason}{(r.CoverAllowed ? "; covers allowed" : "")} |");
        var denied = profileNames.Count(n => DenyList.Rules.Any(r => DenyList.Denies(r, n)));
        L();
        L($"{denied} of {profileNames.Count} profile vars are skipped by the probe. `*DISC*` also catches the sidestick takeover buttons (`S_FC_*_INST_DISCONNECT`); they stay in the profile.");
        L();
        L("### Breakers the probe may touch");
        L();
        L($"All {profileNames.Count(n => n.StartsWith("E_CB_"))} `E_CB_*` stay in the profile. Only these {sample.Count} are marked probeable (spread over the panels): {string.Join(", ", sample.Select(s => $"`{s}`"))}.");
        L();
        L("Breaker names are only panel and grid position, so the scan cannot say which circuit each one protects. Step 2 probes them on the ground, powered, and restores each immediately.");
        L();

        L("## Surprises and things to check");
        L();
        foreach (var s in Surprises(profile, entries, reviews)) L("- " + s);
        L();
        return sb.ToString();
    }

    static IEnumerable<string> Surprises(Profile profile, List<Entry> entries, List<Review> reviews)
    {
        var binary = entries.Count(e => e.Class == "verified" && e.Notes.Any(n => n.StartsWith("values [0,1] from name")));
        if (binary > 0) yield return $"{binary} switches got `values [0, 1]` from their name and a scan value of 0 or 1. The scan has one value per var, so a 3-position switch with a binary-looking name would be limited wrongly. Step 2 must confirm each one; the note on the entry says so.";
        var cbs = entries.Count(e => e.Name.StartsWith("E_CB_"));
        var cbChecked = entries.Count(e => e.Name.StartsWith("E_CB_") && e.Verify is not null);
        yield return cbChecked == 0
            ? $"All {cbs} `E_CB_*` read 1, and the `E_` prefix is the encoder prefix, so they might be counters rather than 0/1 breakers. They are `verified [0, 1]` with the note \"semantics unverified\", as asked."
            : $"{cbChecked} of {cbs} `E_CB_*` were probed: 0/1 breakers, GraphQL `system.switches` mirrors them (their effect check). The other {cbs - cbChecked} keep \"semantics unverified\".";
        var multi = reviews.Count(r => r.Reason.StartsWith("scan value") || r.Reason.StartsWith("name looks multi"));
        yield return $"{multi} switches are on the review list because the position count is unknown (scan value 2 or more, or a multi-position name)."
            + (reviews.Any(r => r.Name == "S_FCU_EFIS2_ND_MODE") ? " `S_FCU_EFIS2_ND_MODE` and `ND_ZOOM` are probably like EFIS1 but are not proven, so they are there too." : "");
        yield return "Many `S_*_Anim` vars read 2 (for example `S_OH_ELEC_GEN1_Anim`): the animation has three states for what looks like a two-position switch. They are `ignore`.";
        var momentary = reviews.Count(r => r.Reason.StartsWith("momentary or latching"));
        yield return $"{momentary} switches are on the review list because momentary or latching cannot be told from the scan: most FCU/EFIS, MIP and flight-control pushbuttons, the audio panels, the RMPs, `_BUTTON`/`_PUSH`/`_UP`/`_DOWN` names. For example the fire buttons are not guessed as pulses. Writing a momentary button as an absolute value would leave it stuck, so these need the step 2 probe.";
        yield return "`*GUARD*` matches nothing in this scan (guards are named `*_Cover`); it stays in the deny list as a catch-all.";
        if (profile.Aircraft.Match.Titles is null) yield return "`match.titles` in the aircraft section is still a TODO (needs the title the sim reports).";
    }

    /// <summary>Reasons that differ only by the scan value or the example names are counted together.</summary>
    static string Generalise(string reason)
    {
        reason = Regex.Replace(reason, @"scan value [\d.\-]+", "scan value 2 or more");
        return Regex.Replace(reason, @"encoder: \d+ possible N_ display vars.*", "encoder: several possible N_ display vars");
    }

    static string Prefix(string name)
    {
        var i = name.IndexOfAny(['_', ':', '.']);
        return i > 0 ? name[..i] + "*" : name;
    }
}
