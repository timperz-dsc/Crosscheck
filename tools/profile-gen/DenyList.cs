// Vars the automated probe (step 2) must never write. They stay in the profile.

using Crosscheck.Profiles;

namespace ProfileGen;

sealed record DenyRule(string Pattern, string Reason, bool CoverAllowed = false, bool BeyondBrief = false);

static class DenyList
{
    public static readonly DenyRule[] Rules =
    [
        new("S_OH_FIRE_*", "fire buttons, extinguisher agents and fire tests (covers too)"),
        new("S_OH_ELEC_IDG*", "IDG disconnect; only the cover may be probed (cover tested in phase 0)", CoverAllowed: true),
        new("S_ENG_MASTER_*", "ENG MASTER"),
        new("S_ENG_MODE", "engine mode selector"),
        new("S_OH_ENG_MANSTART_*", "ENG MAN START (covers too)"),
        new("S_OH_EVAC_*", "EVAC, evacuation horn and captain/purser (covers too)"),
        new("S_OH_OXYGEN_MASK_MAN_ON*", "oxygen MAN ON (cover too)"),
        new("S_OXYGEN_MASK_*", "crew oxygen mask box and mask test"),
        new("S_OH_PNEUMATIC_DITCHING*", "DITCHING (cover too)"),
        new("S_OH_HYD_RAT_MAN_ON", "RAT MAN ON; the cover is not matched, so it stays probeable"),
        new("S_MIP_GEAR", "gear lever"),
        new("S_MIP_PARKING_BRAKE", "parking brake"),
        new("S_OH_ELEC_EMER_GEN_*", "emergency generator test and MAN ON (covers too)"),
        new("*DISC*", "disconnect (IDG, sidestick takeover, cargo): when in doubt deny", CoverAllowed: true),
        new("*EMER*", "emergency: when in doubt deny", CoverAllowed: true),
        new("*GUARD*", "guarded: when in doubt deny", CoverAllowed: true),
        new("S_OH_FLT_CTL_*", "flight control computers ELAC/SEC/FAC (extra, beyond the brief)", BeyondBrief: true),
        new("S_OH_ENG_N1_MODE_*", "engine N1 mode (extra, beyond the brief)", BeyondBrief: true),
        new("S_OH_AFT_FADEC_GND_*", "FADEC ground power (extra, beyond the brief)", BeyondBrief: true),
        new("S_OH_ELT_*", "emergency locator transmitter (extra, beyond the brief)", BeyondBrief: true),
    ];

    public static bool Denies(DenyRule rule, string name) =>
        new ExcludeFilter([rule.Pattern]).IsExcluded(name) && !(rule.CoverAllowed && name.EndsWith("_Cover"));

    /// <summary>Number of names each rule denies.</summary>
    public static Dictionary<DenyRule, int> Hits(IEnumerable<string> names)
    {
        var list = names.ToList();
        return Rules.ToDictionary(r => r, r => list.Count(n => Denies(r, n)));
    }

    /// <summary>About ten breakers, spread over the panels, picked by position in the sorted list.</summary>
    public static List<string> BreakerSample(IEnumerable<string> breakers)
    {
        var byPanel = breakers.OrderBy(b => b, StringComparer.Ordinal)
            .GroupBy(b => b.Split('_')[2]).OrderBy(g => g.Key, StringComparer.Ordinal).ToList();
        var sample = new List<string>();
        foreach (var g in byPanel)
        {
            var items = g.ToList();
            sample.Add(items[items.Count / 3]);
            if (items.Count > 60) sample.Add(items[items.Count * 2 / 3]);
        }
        return sample;
    }
}

static class DenyWriter
{
    static string Q(string s) => "\"" + s.Replace("\"", "\\\"") + "\"";

    public static string Write(IEnumerable<string> breakerSample)
    {
        var sb = new System.Text.StringBuilder();
        sb.Append("# Vars the automated probe (CRO-8 step 2) must never write. Generated by tools/profile-gen.\n");
        sb.Append("# These vars stay in profile.yaml: pilots must be able to sync them. Only the probe skips them.\n");
        sb.Append("# Patterns are globs (* any characters, ? one character, case-sensitive), same as `exclude`.\n");
        sb.Append("# cover_allowed: true = a var ending in _Cover is NOT denied by this pattern.\n");
        sb.Append("format: 1\n\ndeny:\n");
        foreach (var r in DenyList.Rules)
        {
            sb.Append($"  - pattern: {Q(r.Pattern)}\n    reason: {Q(r.Reason)}\n");
            if (r.CoverAllowed) sb.Append("    cover_allowed: true\n");
        }
        sb.Append("\n# E_CB_*: all breakers stay in the profile. Only these may be probed (ground, powered, restored at once).\n");
        sb.Append("# Picked by position from each panel; the scan cannot say which circuit a breaker protects.\n");
        sb.Append("probe_allow:\n  breakers:\n");
        foreach (var b in breakerSample) sb.Append($"    - {b}\n");
        return sb.ToString();
    }
}
